class ThaiLLM(LLM):
    model: str = "kbtg"

    def _call(self, prompt: str, stop: Optional[List[str]] = None, **kwargs: Any) -> str:
        messages = [{"role": "user", "content": prompt}]
        result = ask_llm(messages, model=self.model)
        return result or ""

    @property
    def _llm_type(self) -> str:
        return "thai_llm"

