def clean_markdown(text):
    text = re.sub(r'#+\s+', '', text)
    text = re.sub(r'\*\*', '', text)
    text = re.sub(r'---', '', text)
    text = re.sub(r'—', '', text)
    text = re.sub(r'\|\|', '', text)
    text = re.sub(r'\|[\s\-\:\|]+\|', '', text)
    text = re.sub(r'\|', '', text)
    return text.strip()

